const DEFAULT_CROP_IMAGE = 'https://images.unsplash.com/photo-1500937386664-56d1dfef3854?auto=format&fit=crop&w=600&q=80';

export function getCropImage(cropName) {
  if (!cropName) return DEFAULT_CROP_IMAGE;
  const clean = cropName.toLowerCase().trim();
  for (const [key, url] of Object.entries(CROP_IMAGES)) {
    if (clean.includes(key)) {
      return url;
    }
  }
  return DEFAULT_CROP_IMAGE;
}

